// handlers3 mutation spec.
//
// Unobservable / disproven mutations (documented instead of injected):
// - `if (a == nullptr || v == nullptr)` guards: the harness always resolves both ids and
//   the TS side cannot express a missing attacker/victim, so the null branches are dead.
// - `spark_type_of`'s `truthy(fall) &&` prefix: `to_number(undefined)` is NaN, so the
//   following comparison is already false when `fall` is undefined. Removing `truthy`
//   therefore never changes the produced spark type.
// - `if (truthy(sounds))`: `as_array` already returns nullptr for every non-array value,
//   so dropping the guard changes nothing observable.
// - Non-array `hit_sounds`/`dead_sounds` (e.g. a bare string): TS `for...of` would iterate
//   code units while the port only walks arrays. Real data always carries `string[]`, so
//   this divergence is unreachable.
